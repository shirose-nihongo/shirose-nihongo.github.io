const K = "㐀-鿿々〆ヶ";
/** Tambah furigana ke teks campuran (Indonesia + Jepang). Melempar error kalau ada kanji tanpa bacaan. */
function annotate(t) {
  let s = String(t);
  for (const [a, b] of CTX) s = s.split(a).join(b);
  s = s.replace(new RegExp(`[${K}]+(?!\\[|[${K}])`, "g"), (run, off, all) => {
    if (all[off - 1] === "]") return run;               // jangan sentuh sisa hasil CTX (tidak terjadi; jaga-jaga)
    if (!(run in DICT)) throw new Error(`Bacaan belum ada: ${run}  ← ${t}`);
    return `${run}[${DICT[run]}]`;
  });
  return s;
}
